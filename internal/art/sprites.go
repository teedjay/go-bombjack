package art

import "image"

// Anim is a named animation strip. All frames share the same size.
// Frames face right; the game mirrors them with FlipH (or a negative
// GeoM scale) when facing left.
type Anim struct {
	Name   string
	Frames []*image.RGBA
	FPS    float64
	Loop   bool
}

func (a Anim) Size() (int, int) {
	b := a.Frames[0].Bounds()
	return b.Dx(), b.Dy()
}

