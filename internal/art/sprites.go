func saucerSpin() []*image.RGBA {
	top := `
		................
		................
		................
		................
		......KKKK......
		.....KCWCCK.....
		....KCCCCcCK....
		..KKKKKKKKKKKK..
		.KwwwwwwwwwwwwK.
	`
	bottom := `
		.KgggggggggggggK
		..KKKKKKKKKKKKK.
		....KK....KK....
	`
	lights := []string{
		"KGYGGGRGGGYGGGRK",
		"KGGYGGGRGGGYGGGK",
		"KGGGRGGGYGGGRGGK",
		"KRGGGYGGGRGGGYGK",
	}
	var out []*image.RGBA
	for _, l := range lights {
		out = append(out, sprite16(top+l+bottom))
	}
	return out
}
